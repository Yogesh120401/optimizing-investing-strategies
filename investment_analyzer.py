import yfinance as yf
import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, classification_report
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier, VotingClassifier
from sklearn.tree import DecisionTreeClassifier
from xgboost import XGBClassifier

# Step 1: Download data
ticker = "RELIANCE.NS"
df = yf.download(ticker, start="2018-01-01", end="2024-12-31", auto_adjust=False, group_by='ticker')

# Step 2: Handle MultiIndex or flat columns
if isinstance(df.columns, pd.MultiIndex):
    df.columns = ['_'.join(col).strip() for col in df.columns.values]
    prefix = f"{ticker}_"
else:
    prefix = ""

# Step 3: Reset index and add symbol
df.reset_index(inplace=True)
df['Symbol'] = ticker

# Step 4: Column names with fallback
close_col = f'{prefix}Close' if f'{prefix}Close' in df.columns else 'Close'
open_col = f'{prefix}Open' if f'{prefix}Open' in df.columns else 'Open'
high_col = f'{prefix}High' if f'{prefix}High' in df.columns else 'High'
low_col = f'{prefix}Low' if f'{prefix}Low' in df.columns else 'Low'
adj_col = f'{prefix}Adj Close' if f'{prefix}Adj Close' in df.columns else 'Adj Close'
vol_col = f'{prefix}Volume' if f'{prefix}Volume' in df.columns else 'Volume'

# Step 5: Create target
df['Next_Close'] = df[close_col].shift(-1)
df['Return'] = (df['Next_Close'] - df[close_col]) / df[close_col]
df['Target'] = (df['Return'] > 0.005).astype(int)

# Step 6: Feature engineering
df['Daily_Return'] = (df[close_col] - df[open_col]) / df[open_col]
df['SMA_5'] = df[close_col].rolling(window=5).mean()
df['SMA_10'] = df[close_col].rolling(window=10).mean()
df['EMA_5'] = df[close_col].ewm(span=5, adjust=False).mean()
df['EMA_10'] = df[close_col].ewm(span=10, adjust=False).mean()
df['Rolling_Std'] = df[close_col].rolling(window=5).std()
df['Upper_Band'] = df['SMA_5'] + (2 * df['Rolling_Std'])
df['Lower_Band'] = df['SMA_5'] - (2 * df['Rolling_Std'])

# RSI Calculation
delta = df[close_col].diff()
gain = delta.where(delta > 0, 0)
loss = -delta.where(delta < 0, 0)
avg_gain = gain.rolling(window=14).mean()
avg_loss = loss.rolling(window=14).mean()
rs = avg_gain / avg_loss
df['RSI'] = 100 - (100 / (1 + rs))

# Add time features
df['Month'] = df['Date'].dt.month
df['DayOfWeek'] = df['Date'].dt.dayofweek

# Drop missing rows
df = df.dropna()

# Step 7: Define features and target
features = [open_col, high_col, low_col, close_col, adj_col, vol_col,
            'Daily_Return', 'SMA_5', 'SMA_10', 'EMA_5', 'EMA_10',
            'Rolling_Std', 'Upper_Band', 'Lower_Band', 'RSI', 'Month', 'DayOfWeek']

X = df[features]
y = df['Target']

# Step 8: Scale
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# Step 9: Split data
X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=17)

# Step 10: Models
rf = RandomForestClassifier(n_estimators=100, max_depth=6, random_state=42)
dt = DecisionTreeClassifier(max_depth=5, random_state=21)
xgb = XGBClassifier(use_label_encoder=False, eval_metric='logloss', n_estimators=100, max_depth=5, learning_rate=0.05)

# Ensemble model
voting_model = VotingClassifier(
    estimators=[('rf', rf), ('dt', dt), ('xgb', xgb)],
    voting='soft'
)
voting_model.fit(X_train, y_train)

# Evaluation
predictions = voting_model.predict(X_test)
accuracy = accuracy_score(y_test, predictions)

print(f"\n✅ Voting Ensemble Accuracy: {round(accuracy * 100, 2)}%")
print("\n📋 Classification Report:\n")
print(classification_report(y_test, predictions))

