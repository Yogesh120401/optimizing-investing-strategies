from datetime import datetime, timedelta

# Function to evaluate stock
def evaluate_stock(ticker):
    try:
        # Get 1-year data
        end = datetime.today()
        start = end - timedelta(days=365)
        data = yf.download(ticker, start=start, end=end)

        if data.empty:
            return "❌ No data found. Please check the ticker.", None, None

        # Extract prices
        start_price = float(data['Close'].iloc[0])
        end_price = float(data['Close'].iloc[-1])
        change_pct = ((end_price - start_price) / start_price) * 100

        # Summary text
        summary = f"📊 Start Price: ₹{start_price:.2f}\n📈 End Price: ₹{end_price:.2f}\n🔄 Change: {change_pct:.2f}%\n"
        if change_pct >= 10:
            summary += "\n✅ Appears profitable to invest (strong growth)."
        elif 0 < change_pct < 10:
            summary += "\n⚠️ Mild growth. Consider reviewing fundamentals."
        else:
            summary += "\n❌ Negative return. Not advisable currently."

        # Plot 1: Stock Price Movement
        fig1 = plt.figure(figsize=(10, 4))
        plt.plot(data.index, data["Close"], label="Close Price", color="blue")
        plt.title(f"{ticker.upper()} - Stock Price Last 1 Year")
        plt.xlabel("Date")
        plt.ylabel("Price")
        plt.grid(True)
        plt.legend()
        plt.tight_layout()

        # Plot 2: Success/Failure Bar
        fig2 = plt.figure(figsize=(6, 1.5))
        bar_color = 'green' if change_pct >= 0 else 'red'
        plt.barh(["Return %"], [change_pct], color=bar_color)
        plt.axvline(0, color='black', linestyle='--')
        plt.xlim(-100, 100)
        plt.title("Success vs Failure Indicator")
        plt.tight_layout()

        return summary, fig1, fig2

    except Exception as e:
        return f"❌ Error: {str(e)}", None, None

